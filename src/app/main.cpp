// Where hover feedback comes from: the keyboard's focus while it leads (decision 031), else the pointer,
// once it has moved: content that came under a still pointer isn't lit by it (decision 087).
std::optional<Vec2> hoverPoint(const app::Surface& s)
{
    if (!s.pointer.scrub)
        if (auto focused = keyFocusOn(s)) return focused->point;
    if (s.pointer.still && !s.pointer.scrub) return std::nullopt;
    return s.pointer.at;
}

// What's under the pointer changed without it moving: it lights nothing until it does (decision 087).
void pointerStill(app::Surface& s) { s.pointer.still = true; }

// Tells providers what the pointer is on (Provider::onHover, decision 180): the action a
// click there would send, by where the pointer is, still or not (what it opens comes under
// a still pointer, and must stay open). A bar being dragged keeps the pointer, even off it.
// The new one first, then the old one's leaving: moving from a button onto what it opened
// never reads as leaving both. Kept before the calls: a provider's answer lays out again.
void tellHover(app::Surface& s)
{
    if (!g_providers) return;
    std::optional<Action> now;
    if (s.pointer.scrub) {
        if (auto* bar = std::get_if<Progress>(&s.pointer.scrub->item))
            now = Action{ s.pointer.scrub->providerId, s.pointer.scrub->activityId, seekAction(*bar), 0 };
    } else if (s.pointer.at) {
        if (auto hit = hitTest(s.scene, *s.pointer.at)) now = hit->action;
    }
    if (now) now->value = 0, now->text.clear(); // what it's on, not where on it
    std::optional<Action> was = s.pointer.hover;
    if (now == was) return;
    s.pointer.hover = now;
    if (now) g_providers->hover(*now, true);
    if (was) g_providers->hover(*was, false);
}

void updateHover(app::Surface& s)
{
    tellHover(s);
    std::optional<Vec2> at = hoverPoint(s);
    // The top band (decision 108): it glows, and what's under it doesn't light up: a click there closes.
    bool onTop = at && !s.pointer.scrub && inCollapseZone(s.scene, *at);
    s.renderer->setTopGlow(onTop);
    std::string key;
    if (s.pointer.scrub) {
        key = s.pointer.scrub->key; // stays lit while dragged, even off the bar
    } else if (at && !onTop) {
        // Lit only over its shape (decision 130): a click still takes all of its area.
        if (auto hit = hitTest(s.scene, *at); hit && (!findElement(s, hit->key) || lightsAt(*findElement(s, hit->key), *at))) key = hit->key;
    }
    s.renderer->setHovered(key);
    // A text field shows the I-beam (decision 043): the add field, and a to-do only while it's
    // being edited (then it's a field); a field being drag-selected keeps it, even off it.
    // The cursor is where the pointer is, still or not (decision 087 holds back only what lights up).
    auto cursorHit = s.pointer.at && !s.pointer.scrub ? hitTest(s.scene, *s.pointer.at) : std::nullopt;
    const Placed* under = cursorHit ? findElement(s, cursorHit->key) : nullptr;
    bool text = !s.pointer.selecting.empty() || (under && std::holds_alternative<TextInput>(under->item));
    setTextCursor(text);
    s.renderer->setHoveredRow(at ? rowAt(s.scene, *at) : std::string()); // reveals a to-do's delete button, the plan's − and + (decision 063)

    // Tabs light up as a whole, except the active one, which is already marked (decision 007).
    const Tab* tab = s.scene.tabs && at && !onTop ? tabAt(*s.scene.tabs, *at) : nullptr;
    if (tab && isCurrent(s, *tab)) tab = nullptr;
    s.renderer->setHoveredTab(tab ? std::optional<std::string>(tab->id) : std::nullopt); // its grey content in colour (decision 072)
    // A list item (a to-do) lights up as a whole row, like a tab (Row::listItem).
    bool onMenu = at && s.scene.menu && s.scene.menu->frame.contains(*at); // a row's menu covers what's under it (decision 086)
    const Placed* item = at && !s.pointer.scrub && !onMenu ? contentUnder(s, *at) : nullptr;
    if (tab) s.renderer->setAreaHovered(tab->lit, tab->radius); // a page-row button's shape
    else if (item && item->listRow) s.renderer->setAreaHovered(item->listRow, item->listRowRadius);
    else if (auto lit = &s == &g_island && escapeCloses(g_state) && !app::keyFocus() ? defaultRow(s.scene) : std::nullopt)
        s.renderer->setAreaHovered(lit->frame, lit->radius); // typing in search: the row Enter opens (decision 079)
    else s.renderer->setAreaHovered(std::nullopt, 0);

    // The keyboard's focus also gets a ring (decision 033): hover alone can't
    // tell it from the pointer's, and a static widget has no hover at all.
    std::optional<cup::Focusable> focused;
    if (!s.pointer.scrub) focused = keyFocusOn(s);
    if (focused && inView(*focused)) s.renderer->setFocusRing(focused->frame, focused->radius);
    else s.renderer->setFocusRing(std::nullopt, 0);
}

std::optional<Ms> earliest(std::optional<Ms> a, std::optional<Ms> b)
{
    if (!a) return b;
    if (!b) return a;
    return std::min(*a, *b);
}

// One timer for everything time-based: core deadlines, ticking labels and provider wake-ups.
void armDeadline(Ms t)
{
    auto deadline = earliest(earliest(nextDeadline(g_state), sceneDeadline(g_island.scene)), tintDeadline(g_tint));
    if (g_providers) deadline = earliest(deadline, g_providers->nextWake());
    if (g_dialogIsland) { // the one timer is for both islands (decision 181)
        deadline = earliest(deadline, earliest(nextDeadline(g_other.state), sceneDeadline(g_other.surface.scene)));
        if (g_other.providers) deadline = earliest(deadline, g_other.providers->nextWake());
    }
    setTimer(TimerId::Deadline, deadline ? std::optional<Ms>(std::max(*deadline - t, Ms{ 0 })) : std::nullopt);
}

