// A dialog's own buttons (decision 020): Cancel just closes it; the confirm
// button sends the provider its action, then closes it.
void answerDialog(bool confirmed)
{
    const Dialog* over = shownDialog(g_state);
    if (!over) return;
    Dialog asked = *over;
    dispatch(DialogClosed{}, confirmed ? "dialog confirmed" : "dialog cancelled");
    if (confirmed) g_providers->route({ asked.providerId, asked.activityId, asked.confirmAction, 0 });
}

// A clicked button: the host's dialog answers itself; anything else goes to its provider.
void act(const Action& action)
{
    if (action.actionId == kDialogConfirm || action.actionId == kDialogCancel) { // host-owned names: never a provider's
        answerDialog(action.actionId == kDialogConfirm);
        return;
    }
    g_providers->route(action);
    const Toast* toast = toastOn(g_state, action.activityId);
    if (toast && action.actionId == toast->actionId) dispatch(ToastClosed{}, "toast acted"); // done: it goes (decision 071)
    dispatch(PointerMoved{}, "action"); // the user is busy here: keep Expanded open
}

// The wheel over a list scrolls it, from what's shown (decision 029); the renderer eases it there.
void onWheel(app::Surface& s, Vec2 canvasPoint, float notches)
{
    s.pointer.still = false; // the wheel is the pointer at work: what scrolls under it lights (decision 087)
    const Placed* p = listAt(s.scene, toLocal(s, canvasPoint));
    if (!p) return;
    dispatch(ListScrolled{ p->activityId, p->list->id, p->list->offset, notches * tokens().scrollStep, p->list->max }, "scroll");
}

// An edit button (Button::editsText): its row's text becomes a field holding it (decision 029).
bool startEditing(app::Surface& s, const Placed& element)
{
    auto* button = std::get_if<Button>(&element.item);
    if (!button || !button->editsText) return false;
    const Text* text = editedText(s.scene, element.activityId, button->actionId);
    if (!text) return true; // nothing to edit on screen: the click does nothing
    SetFocus(s.input);
    dispatch(InputFocused{ element.providerId, element.activityId, button->actionId, text->value, /* editing */ true, std::nullopt,
                           text->editMaxLength }, "edit");
    return true;
}

// The text being edited in place is kept when the user moves on (a click
// elsewhere, another field, the card closing), like any text box; only Esc drops it.
void finishEditing(const char* reason)
{
    if (!g_state.draft || !g_state.draft->editing) return;
    const Draft& d = *g_state.draft;
    g_providers->route({ d.providerId, d.activityId, d.actionId, 0, d.text });
    dispatch(InputSubmitted{}, reason);
}

// A press in a field (decision 043): focuses it with the caret where it was
// pressed; again, the second press selects a word, the third everything.
// Dragging from there selects (onPointerMoved).
void pressField(app::Surface& s, const Placed& field, Vec2 canvasPoint, Vec2 point)
{
    const auto& input = std::get<TextInput>(field.item);
    Ms t = now();
    bool sameSpot = std::abs(canvasPoint.x - s.pointer.lastClickPoint.x) <= GetSystemMetrics(SM_CXDOUBLECLK) / 2 &&
                std::abs(canvasPoint.y - s.pointer.lastClickPoint.y) <= GetSystemMetrics(SM_CYDOUBLECLK) / 2;
    s.pointer.clicks = input.focused && sameSpot && t - s.pointer.lastClickAt <= Ms{ GetDoubleClickTime() } ? s.pointer.clicks % 3 + 1 : 1;
    s.pointer.lastClickAt = t;
    s.pointer.lastClickPoint = canvasPoint;
    s.pointer.selecting = field.key;
    std::size_t at = s.renderer->caretAt(field, point);
    SetFocus(s.input);
    if (!input.focused) dispatch(InputFocused{ field.providerId, field.activityId, input.actionId, {}, false, at, input.maxLength }, "focus field");
    else if (s.pointer.clicks == 2) dispatch(WordSelected{ at }, "select word");
    else if (s.pointer.clicks == 3) dispatch(AllSelected{}, "select all");
    else dispatch(CaretPlaced{ at, GetKeyState(VK_SHIFT) < 0 }, "place caret");
}

// A list row let go after a drag: the drag ends first (the row glides back),
// then its provider moves it, so the glide carries on to the new place.
void dropListRow(app::Surface& s, bool commit)
{
    std::optional<Placed> dragged;
    for (const Placed& p : s.scene.elements)
        if (p.list && p.list->dragged) dragged = p;
    dispatch(ListDragEnded{}, commit ? "drop row" : "drag cancelled");
    if (commit && dragged && dragged->list->dropAt != dragged->list->row)
        g_providers->route({ dragged->providerId, dragged->activityId, dragged->list->moveAction, static_cast<float>(dragged->list->dropAt) });
}

// A level's bar (a volume) is heard as it's dragged, not only when it's let
// go (Progress::level, decision 180): its action at every step. By value:
// the provider's update lays the scene out again.
void routeLevel(Placed bar, float fraction)
{
    auto* level = std::get_if<Progress>(&bar.item);
    if (level && level->level) g_providers->route({ bar.providerId, bar.activityId, seekAction(*level), fraction });
}

// Mouse-down: the bubble may become a drag, a progress bar starts scrubbing,
// a button gets its own press feedback, anything else squashes the pill.
void onPressDown(app::Surface& s, Vec2 canvasPoint)
{
    s.pointer.still = false; // pressed: the pointer is in use (decision 087)
    if (app::menuPress(toLocal(s, canvasPoint))) return; // an open menu takes the press (decision 086)
    g_drag = trackPointer({}, canvasPoint, now(), tokens());
    if (!onBubble(s, canvasPoint)) {
        // Held still, the island lifts (decision 026). Core ignores it where
        // it can't (Expanded), and then the press is only what it always was.
        // The dialog's island stays with its dialog (decision 181).
        if (g_seat == Seat::Island) dispatch(IslandPressed{}, "press");
        if (g_state.pressedAt) s.pointer.islandPress = canvasPoint;
    }
    if (onBubble(s, canvasPoint)) {
        s.pointer.bubblePress = canvasPoint;
        s.pointer.dragged = false;
        s.renderer->pressDown(true);
        return;
    }
    Vec2 point = toLocal(s, canvasPoint);
    s.pointer.at = point;
    if (inCollapseZone(s.scene, point)) { // the top band: over tabs and buttons, it closes (decision 108)
        s.pointer.topPress = true;
        s.renderer->pressDown(false);
        return;
    }
    if (const Tab* tab = tabUnder(s, point)) {
        s.pointer.tabPress = tab->id; // switches on release, if still on the same tab
        return;
    }
    auto hit = hitTest(s.scene, point);
    const Placed* element = hit ? findElement(s, hit->key) : nullptr;
    auto* field = element ? std::get_if<TextInput>(&element->item) : nullptr;
    if (g_state.draft && g_state.draft->editing && !(field && field->focused)) {
        finishEditing("edit kept"); // pressed away from the text being edited
        hit = hitTest(s.scene, point); // the list may have changed under it
        element = hit ? findElement(s, hit->key) : nullptr;
    }
    if (element && std::holds_alternative<TextInput>(element->item)) {
        pressField(s, *element, canvasPoint, point);
        return;
    }
    if (element && std::holds_alternative<Progress>(element->item)) {
        s.pointer.scrub = *element;
        s.pointer.scrubFraction = hit->action.value;
        s.renderer->scrubElement(hit->key, s.pointer.scrubFraction);
        routeLevel(*s.pointer.scrub, s.pointer.scrubFraction); // a volume: set from the press on
    } else if (element) {
        s.pointer.pressedKey = hit->key;
        s.pointer.textPress = point;
        s.renderer->pressElement(hit->key);
        // A row that can be reordered: dragged far enough, it's picked up instead of clicked.
        if (element->list && !element->list->moveAction.empty()) {
            s.pointer.listPress = *element;
            s.pointer.listPressY = point.y;
        }
    } else if (pressSquashes(g_state)) { // not where an empty click does nothing (decision 071)
        s.renderer->pressDown(false);
    }
    updateHover(s);
}

void onPointerMoved(app::Surface& s, Vec2 canvasPoint, bool inside)
{
    // Lifted and past its monitor's edge: onto the next one first, so the rest is in its coordinates (decision 178).
    if (s.pointer.islandPress && g_state.lift) canvasPoint = carriedAcross(canvasPoint);
    app::pointerMoved(canvasPoint); // a real move takes the lead back from the keyboard
    // Windows repeats a move, at the same point, when windows change under a
    // still pointer: only a real one lets it light things (decision 087).
    bool moved = s.pointer.lastMove != canvasPoint;
    s.pointer.lastMove = canvasPoint;
    if (moved) s.pointer.still = false;
    if (moved) app::menuPointerMoved(toLocal(s, canvasPoint)); // lights the menu's item under it (decision 086)
    if (s.pointer.islandPress || s.pointer.bubblePress) g_drag = trackPointer(g_drag, canvasPoint, now(), tokens());
    if (s.pointer.islandPress) {
        Vec2 start = *s.pointer.islandPress;
        dispatch(IslandDragged{ { canvasPoint.x - start.x, canvasPoint.y - start.y } }, "lift drag");
        if (g_state.lift) return; // carried: nothing under it reacts
    }
    if (s.pointer.bubblePress) {
        Vec2 start = *s.pointer.bubblePress;
        dispatch(BubbleDragged{ { canvasPoint.x - start.x, canvasPoint.y - start.y } }, "drag");
        if (g_state.bubbleDrag && !s.pointer.dragged) {
            s.pointer.dragged = true;
            s.renderer->pressRelease(true); // un-squash: it's being carried now
        }
        return;
    }
    Vec2 point = toLocal(s, canvasPoint);
    s.pointer.at = inside && onShape(s, canvasPoint) ? std::optional<Vec2>(point) : std::nullopt;
    if (const Placed* field = s.pointer.selecting.empty() || !g_state.draft ? nullptr : findElement(s, s.pointer.selecting)) {
        std::size_t at = s.renderer->caretAt(*field, point); // off either end: its first or last character
        if (at != g_state.draft->caret) dispatch(CaretPlaced{ at, true }, "select");
        return;
    }
    if (s.pointer.listPress) {
        const Placed& row = *s.pointer.listPress;
        if (!g_state.listDrag && std::abs(point.y - s.pointer.listPressY) >= tokens().dragStartDistance) {
            if (!s.pointer.pressedKey.empty()) s.renderer->releaseElement(std::exchange(s.pointer.pressedKey, std::string{})); // not a click now
            dispatch(ListDragStarted{ row.activityId, row.list->id, row.list->row, s.pointer.listPressY, row.list->offset }, "pick up row");
        }
        if (g_state.listDrag) {
            dispatch(ListDragMoved{ point.y }, "carry row");
            return;
        }
    }
    if (s.pointer.scrub) {
        s.pointer.scrubFraction = seekFraction(*s.pointer.scrub, point.x);
        s.renderer->scrubElement(s.pointer.scrub->key, s.pointer.scrubFraction);
        // A level (a volume) is heard as it's dragged, not only when it's let go (decision 180).
        routeLevel(*s.pointer.scrub, s.pointer.scrubFraction);
    }
    dispatch(PointerMoved{}, "pointer"); // keeps Expanded open while in use; refreshes hover
}

// What a click does, by what it's on. The pointer's release and the keyboard's Enter share them.
void clickTab(const std::string& id)
{
    if (id.rfind(kPanelButtonTab, 0) == 0) { // a panel's button (decision 113): its tap action, or its card
        const Panel* panel = findPanel(g_state, id.substr(std::string(kPanelButtonTab).size()));
        if (panel && !panel->tapAction.empty()) {
            g_providers->route({ panel->providerId, panel->id, panel->tapAction, 0 });
            dispatch(PointerMoved{}, "page row button"); // the user is busy here: keep the card open
        } else if (panel) {
            dispatch(CardOpened{ panel->id }, "page row button"); // no tap action: its card (Search, decision 165)
        }
        return;
    }
    dispatch(ActivitySwitched{ id }, "tab"); // a page's icon: its card, running or not (decision 165)
}

// `at`: where a click was (pill coordinates); none for Enter or Space.
void clickElement(app::Surface& s, const Hit& hit, std::optional<Vec2> at = std::nullopt)
{
    if (hit.action.actionId == kMenuOpen) { // a row's ›: its menu, beside the row (decision 086)
        dispatch(MenuOpened{ hit.action.activityId, rowKeyOf(hit.key), std::nullopt }, "row's menu button");
        return;
    }
    const Placed* element = findElement(s, hit.key);
    auto* text = element ? std::get_if<Text>(&element->item) : nullptr;
    if (text && !text->editAction.empty()) {
        // Its text: edit it in place, the caret where it was clicked, else at its end (decision 043).
        std::optional<std::size_t> caret;
        if (at) caret = s.renderer->caretAt(*element, *at);
        SetFocus(s.input);
        dispatch(InputFocused{ element->providerId, element->activityId, text->editAction, text->value, true, caret, text->editMaxLength }, "edit");
    } else if (element && std::holds_alternative<TextInput>(element->item)) {
        // A field: focus it for typing (decision 016); nothing is sent until Enter.
        SetFocus(s.input);
        dispatch(InputFocused{ hit.action.providerId, hit.action.activityId, hit.action.actionId, {}, false, std::nullopt,
                               std::get<TextInput>(element->item).maxLength }, "focus field");
    } else if (!element || !startEditing(s, *element)) {
        act(hit.action);
    }
}

void onPressRelease(app::Surface& s, Vec2 canvasPoint, Release how)
{
    if (app::menuRelease(toLocal(s, canvasPoint))) { // ...and its release (decision 086)
        updateHover(s);
        return;
    }
    if (s.pointer.islandPress) {
        s.pointer.islandPress.reset();
        bool lifted = g_state.lift.has_value();
        dispatch(IslandReleased{}, lifted ? "landed" : "release");
        if (lifted) return; // it was carried, not clicked; lost capture lands it too
    }
    if (!std::exchange(s.pointer.selecting, std::string{}).empty()) {
        updateHover(s);
        return; // the caret and selection are where the drag left them
    }
    if (std::exchange(s.pointer.topPress, false)) {
        s.renderer->pressRelease(false);
        if (how == Release::Inside && onShape(s, canvasPoint) && inCollapseZone(s.scene, toLocal(s, canvasPoint)))
            dispatch(TopClicked{}, "top click");
        return;
    }
    if (s.pointer.tabPress) {
        std::string id = *std::exchange(s.pointer.tabPress, std::nullopt);
        const Tab* tab = how == Release::Inside && onShape(s, canvasPoint) ? tabUnder(s, toLocal(s, canvasPoint)) : nullptr;
        if (tab && tab->id == id && !isCurrent(s, *tab)) clickTab(id);
        return;
    }
    if (s.pointer.bubblePress) {
        s.pointer.bubblePress.reset();
        if (!s.pointer.dragged) s.renderer->pressRelease(true);
        if (g_state.bubbleDrag) dispatch(how == Release::Cancelled ? Event{ BubbleDragCancelled{} } : Event{ BubbleReleased{} }, "drop");
        else if (!s.pointer.dragged && how == Release::Inside && onBubble(s, canvasPoint)) dispatch(BubbleClicked{}, "bubble click");
        return;
    }
    if (std::exchange(s.pointer.listPress, std::nullopt) && g_state.listDrag) {
        dropListRow(s, how != Release::Cancelled); // dropped anywhere: it lands where it shows it would
        return;
    }
    Vec2 point = toLocal(s, canvasPoint);
    if (s.pointer.scrub) {
        // A scrub seeks wherever it's let go, even off the pill; only a lost capture cancels it.
        Placed bar = *std::exchange(s.pointer.scrub, std::nullopt);
        bool commit = how != Release::Cancelled;
        s.renderer->endScrub(bar.key, commit ? std::optional<float>(s.pointer.scrubFraction) : std::nullopt, now());
        auto* progress = std::get_if<Progress>(&bar.item);
        if (commit) g_providers->route({ bar.providerId, bar.activityId, progress ? seekAction(*progress) : "seek", s.pointer.scrubFraction });
        dispatch(PointerMoved{}, "seek");
        return;
    }
    if (!s.pointer.pressedKey.empty()) {
        std::string key = std::exchange(s.pointer.pressedKey, std::string{});
        s.renderer->releaseElement(key);
        // Only a release on the same button counts: sliding off cancels, like any button.
        auto hit = how == Release::Inside && onShape(s, canvasPoint) ? hitTest(s.scene, point) : std::nullopt;
        if (hit && hit->key == key) clickElement(s, *hit, s.pointer.textPress);
        return;
    }
    s.renderer->pressRelease(false);
    // A click on a disabled control does nothing, as it does nothing there: it doesn't close the card either.
    if (how == Release::Inside && onShape(s, canvasPoint) && !hitTest(s.scene, point) && !onDisabledControl(s.scene, point))
        dispatch(PillClicked{}, "click");
}

// Sends the focused field's text to its provider: what was typed (Enter), or
// the clipboard (Ctrl+V: the provider splits lines into items).
void sendDraft(const std::string& text)
{
    const Draft& d = *g_state.draft;
    if (!text.empty()) g_providers->route({ d.providerId, d.activityId, d.actionId, 0, text });
}

// Ctrl+V (decision 043): one line goes in at the caret, like any text box.
// Several lines in the add field are sent at once, a to-do each (decision
// 016); edited in place, a to-do takes the first of them.
void paste()
{
    std::string clip = readClipboardText(g_inputHwnd);
    std::vector<std::string> lines;
    std::istringstream in(clip);
    for (std::string line; std::getline(in, line);) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.find_first_not_of(" \t") != std::string::npos) lines.push_back(line);
    }
    if (lines.size() > 1 && !g_state.draft->editing) {
        sendDraft(clip);
        dispatch(PointerMoved{}, "paste lines"); // busy: keep the card open
    } else if (!lines.empty()) {
        dispatch(TextTyped{ lines.front() }, "paste");
    }
}

// Typed text, for the focused field (decision 016). Enter sends, Backspace
// erases (Ctrl: a word), Ctrl+A/C/X/V select all, copy, cut and paste
// (decision 043); other control characters are ignored.
void onChar(wchar_t c)
{
    static wchar_t highSurrogate = 0; // the first half of a character outside the BMP (emoji)
    if (app::swallowChar()) return;   // a key a row's menu took: Enter, Space, a letter, a shortcut (decision 086)
    if (!g_state.draft) return;
    if (c == L'\r') {
        if (escapeCloses(g_state) && app::activateFocused()) return; // a highlighted row: Enter opens it (decision 079)
        sendDraft(g_state.draft->text);
        dispatch(InputSubmitted{}, "enter");
    } else if (c == L'\b' || c == 0x7F) { // 0x7F: Ctrl+Backspace
        dispatch(TextErased{ false, c == 0x7F }, "backspace");
    } else if (c == 0x01) { // Ctrl+A
        dispatch(AllSelected{}, "select all");
    } else if (c == 0x03 || c == 0x18) { // Ctrl+C, Ctrl+X
        std::string selected = selectedText(*g_state.draft);
        if (selected.empty() || !writeClipboardText(g_inputHwnd, selected)) return;
        if (c == 0x18) dispatch(TextErased{}, "cut");
    } else if (c == 0x16) { // Ctrl+V
        paste();
    } else if (c >= 0xD800 && c <= 0xDBFF) {
        highSurrogate = c;
    } else if (c >= 0x20) {
        wchar_t pair[2] = { highSurrogate, c };
        bool low = highSurrogate && c >= 0xDC00 && c <= 0xDFFF;
        dispatch(TextTyped{ toUtf8(low ? std::wstring_view(pair, 2) : std::wstring_view(&c, 1)) }, "typing");
        highSurrogate = 0;
    }
}

void onKey(WPARAM key)
{
    app::clearCharSwallow();
    pointerStill(g_island); // typing changes what's under the pointer (search's results): it waits for a move (decision 087)
    if (app::recordKey(key, false)) return; // a key on the island while Settings records a shortcut: it stops waiting (decision 032)
    bool ctrl = GetKeyState(VK_CONTROL) < 0, alt = GetKeyState(VK_MENU) < 0;
    // A dialog: Esc cancels it, the card stays (decision 020). The arrows,
    // Tab and Enter move between its buttons and press one (decision 033);
    // the first press shows focus on Cancel, so a stray Enter answers nothing.
    // No Ctrl or Alt keys: switching tabs or closing would leave it hanging.
    if (shownDialog(g_state)) {
        if (key == VK_ESCAPE) answerDialog(false);
        else if (!ctrl && !alt) app::navigationKey(key);
        return;
    }
    // A row's menu (decision 086): its items' shortcuts on the lit row, and the keys in it while it's open.
    // The Menu key and Shift+F10 open it, as anywhere in Windows.
    if (app::menuKey(key)) return;
    if (key == VK_APPS || (key == VK_F10 && GetKeyState(VK_SHIFT) < 0)) {
        app::openMenuByKeys();
        return;
    }
    // A focused field gets the keys (onChar): no demo keys while typing. Esc
    // stops typing; a second Esc closes the card. A card that is its field
    // (search) closes at the first (decision 079).
    if (g_state.draft) {
        bool shift = GetKeyState(VK_SHIFT) < 0;
        switch (key) {
        case VK_ESCAPE:
            if (escapeCloses(g_state)) dispatch(EscapePressed{}, "esc");
            else dispatch(InputCancelled{}, "esc");
            break;
        // Moving the caret (decision 043): Shift selects, Ctrl goes a word at a time.
        case VK_LEFT: dispatch(CaretMoved{ ctrl ? CaretMove::WordLeft : CaretMove::Left, shift }, "caret"); break;
        case VK_RIGHT: {
            // On a card that is its field (search), Right at the text's end, or on a row highlighted
            // with Down, opens the lit row's menu: the caret has nowhere to go (decision 086).
            const Draft& d = *g_state.draft;
            bool atEnd = d.caret == d.text.size() && d.anchor == d.caret;
            if (escapeCloses(g_state) && !ctrl && !shift && (atEnd || app::keyFocus()) && app::openMenuByKeys()) break;
            dispatch(CaretMoved{ ctrl ? CaretMove::WordRight : CaretMove::Right, shift }, "caret");
            break;
        }
        case VK_HOME: dispatch(CaretMoved{ CaretMove::Start, shift }, "caret"); break;
        case VK_END: dispatch(CaretMoved{ CaretMove::End, shift }, "caret"); break;
        case VK_UP:
        case VK_DOWN: { // a line up or down in wrapped text (decision 045); from the first or last line, its start or end
            if (escapeCloses(g_state) && app::fieldCardKey(key)) break; // a card that is its field: through its rows (decision 079)
            const Placed* field = nullptr;
            app::Surface& keys = g_island;
            for (const Placed& p : keys.scene.elements)
                if (auto* input = std::get_if<TextInput>(&p.item); input && input->focused) field = &p;
            auto at = field ? keys.renderer->caretOnLine(*field, key == VK_UP ? -1 : 1) : std::nullopt;
            if (at) dispatch(CaretPlaced{ *at, shift }, "caret line");
            else dispatch(CaretMoved{ key == VK_UP ? CaretMove::Start : CaretMove::End, shift }, "caret");
            break;
        }
        case VK_DELETE: dispatch(TextErased{ true, ctrl }, "delete"); break;
        }
        return;
    }
    // Alt combinations (WM_SYSKEYDOWN) are only for recording a shortcut; Windows handles the rest (not Alt+F4: decision 049).
    if (alt) return;
    if (app::navigationKey(key)) return; // the arrows, Tab, Home/End, Enter and Space (decisions 031, 033)
    switch (key) {
    case VK_ESCAPE: {
        // One step back, never out of the app: quitting is the tray's Exit. A
        // card's own page goes back to its list, anything else closes (decision 033).
        if (mode(g_state) != Mode::Expanded) return;
        std::string back = backAction(g_state);
        if (auto card = shownCard(g_state); card && !back.empty()) act({ card->providerId, card->activityId, back });
        else dispatch(EscapePressed{}, "esc");
        return;
    }
    }
    // Ctrl+W: asks the shown activity's provider to close it, which may end
    // it, ask first or ignore it (decision 034). A dormant card has
    // no activity to close.
    if (ctrl && key == 'W') {
        auto card = shownActivity(g_state);
        if (mode(g_state) == Mode::Expanded && card) {
            g_providers->closeRequested(*card);
            dispatch(PointerMoved{}, "close request"); // busy here: keep the card open for an answer
        }
        return;
    }
    if (ctrl || !kDemoKeys) return; // the demo keys are plain letters (Ctrl+M isn't M), in Debug builds only
    switch (key) {
    case 'M': toggleProvider("demo"); break;
    case 'T': toggleTimer(); break;
    case 'C': {
        Content content{ .label = "Battery 5%", .alertLeading = { row({ Icon{ Glyph::Warning } }) },
                         .alertCenter = { row({ Text{ "Battery 5%", TextStyle::Title } }), row({ Text{ "Plug in soon" } }) } };
        dispatch(AlertPosted{ { .level = Level::Critical, .content = content } }, "demo key");
        break;
    }
    case 'D':
        if (g_state.dragging) dispatch(DragLeft{}, "demo key");
        else dispatch(DragEntered{ true }, "demo key");
        break;
    case 'H': dispatch(HiddenChanged{ !g_state.hidden }, "demo key"); break;
    }
}

// New tokens are active (a tokens.json save, or a new display scale): resize
// the render layer if the canvas changed, rebuild the content, re-layout.
// The render layer and the interaction layer, centred at the top of the island's monitor.
// `carriedAt`: a lifted island was carried here (screen pixels) from another
// monitor (decision 178): it goes on from under the pointer, still lifted.
void positionLayers(std::optional<Vec2> carriedAt = std::nullopt)
{
    At island(Seat::Island); // the island's layers, whoever asks
    Display display = displayFor(g_displayId);
    g_displayBounds = display.bounds;
    resizeRenderLayer(g_render, tokens().canvas, g_displayBounds);
    std::optional<Vec2> window;
    if (carriedAt) {
        // The window (it has capture, so where hardly matters) goes under the
        // pointer too: left at its old offset it could be on a third monitor,
        // and Windows would report that one's scaling.
        Rect was = interactiveBounds(g_island.scene);
        float room = std::max(static_cast<float>(g_render.width) - was.width, 0.0f);
        window = Vec2{ std::clamp(carriedAt->x - static_cast<float>(g_render.left) - was.width / 2, 0.0f, room), was.y };
    }
    setRenderOrigin(g_island.input, g_render.left, g_render.top, window);
    renderer().layerChanged(); // liquid glass draws at the layer's size, from its monitor's picture (decision 165)
    float width = static_cast<float>(g_render.width);
    if (carriedAt) dispatch(IslandCarried{ width, carriedAt->x - static_cast<float>(g_render.left) }, "carried to another monitor");
    else dispatch(ScreenResized{ width }, "screen");
}

// The lift began (decision 026): what the press started on gives up (a
// button isn't clicked, a scrub doesn't seek) and the pill un-squashes.
void onLifted()
{
    if (!g_island.pointer.pressedKey.empty()) renderer().releaseElement(std::exchange(g_island.pointer.pressedKey, std::string{}));
    if (g_island.pointer.scrub) renderer().endScrub(std::exchange(g_island.pointer.scrub, std::nullopt)->key, std::nullopt, now());
    renderer().pressRelease(false);
    g_island.pointer.at.reset();
    updateHover(g_island);
}

// Where the island rests on this monitor, kept for the next start (decision 026).
void saveSpot()
{
    auto it = g_spots.find(g_displayId);
    if (it != g_spots.end() && it->second == g_state.spot) return;
    g_spots[g_displayId] = g_state.spot;
    writeTextFile(g_spotsFile, formatSpots(g_spots));
}

Spot savedSpot(const std::string& displayId)
{
    auto it = g_spots.find(displayId);
    return it == g_spots.end() ? Spot{} : it->second;
}

// Windows' "Animation effects" (Settings > Accessibility > Visual effects): off, motion is reduced (decision 080).
bool animationsOff()
{
    BOOL on = TRUE;
    return SystemParametersInfoW(SPI_GETCLIENTAREAANIMATION, 0, &on, 0) && !on;
}

// Windows' app mode (Settings > Personalization > Colors): light, unless it says dark. Read each time.
bool appsLight()
{
    DWORD value = 1, size = sizeof value;
    RegGetValueW(HKEY_CURRENT_USER, L"Software\\Microsoft\\Windows\\CurrentVersion\\Themes\\Personalize", L"AppsUseLightTheme", RRF_RT_REG_DWORD,
                 nullptr, &value, &size);
    return value != 0;
}

// Providers' windows in their own theme (decision 150), as Settings picked it;
// System's follows Windows' app mode, so this runs again when that changes.
void applyWindowTheme()
{
    if (app::setWindowTheme(windowThemeFor(g_windowTheme, g_windowThemeName, appsLight(), tokens().themes))) app::refreshWindows();
}

void tokensChanged(Vec2 oldCanvas, const char* reason)
{
    At island(Seat::Island);
    if (tokens().canvas != oldCanvas) positionLayers();
    renderer().refreshAnimations(); // also drops content visuals, so they're redrawn at the new sizes
    app::refreshWindows();          // providers' windows too: a theme recolours them (decision 104)
    dispatch(Tick{}, reason);
    if (!g_dialogIsland) return;
    // The file dialog's island too (decision 181): its layer is the canvas's size.
    At dialog(Seat::Dialog);
    renderer().refreshAnimations();
    dispatch(ScreenResized{ tokens().canvas.x }, reason);
    app::refitFilePicker();
}

// Display scale changed (Settings, or the primary display was swapped): every
// length is rescaled (decision 017).
void onDpiChanged(float scale)
{
    Vec2 oldCanvas = tokens().canvas;
    if (app::rescaleTokens(g_tokensFile, scale)) tokensChanged(oldCanvas, "display scale");
}

void onTimer(TimerId id)
{
    if (id == TimerId::Deadline) {
        if (g_dialogIsland) { // the file dialog's island shares the timer (decision 181)
            At dialog(Seat::Dialog);
            g_providers->wakeDue(now());
            dispatch(Tick{}, "timer");
        }
        g_providers->wakeDue(now());
        // Re-read the wall clock every time: it also does Tick's work, and a
        // clock or time-zone change shows within a minute (decision 009).
        dispatch(readWallClock(), "timer");
    } else if (id == TimerId::TokensReload) {
        Vec2 oldCanvas = tokens().canvas;
        if (!app::loadTokens(g_tokensFile, /* startup */ false)) return;
        tokensChanged(oldCanvas, "tokens.json");
        g_settings->refresh(); // the themes may have changed
    }
}

// Put the island on this monitor ("" = the main display, also the fallback
// for one that isn't connected), at that monitor's scaling (decisions 017, 023).
// Also re-run on any display change: the same monitor may have moved or resized.
// `carriedAt`: lifted, it was carried there by the pointer (screen pixels,
// decision 178): it stays lifted and lands where it's let go, so its saved
// spot on that monitor isn't restored.
void placeIsland(const std::string& displayId, std::optional<Vec2> carriedAt)
{
    g_displayId = displayId;
    Display display = displayFor(displayId);
    Vec2 oldCanvas = tokens().canvas;
    bool rescaled = app::rescaleTokens(g_tokensFile, display.scale);
    if (!carriedAt) dispatch(SpotRestored{ savedSpot(displayId) }, "display"); // each monitor keeps its own (decision 026)
    positionLayers(carriedAt);
    if (rescaled) tokensChanged(oldCanvas, "display");
    logLine("island on %s (%.0f%%)%s", display.name.c_str(), display.scale * 100, carriedAt ? ", carried there" : "");
}

// A lifted island carried past its monitor's edge is on the monitor under the
// pointer from then on (decision 178), and starts there next time. Returns
// the point in the render layer's coordinates: the new monitor's after a move.
Vec2 carriedAcross(Vec2 canvasPoint)
{
    Vec2 screen{ static_cast<float>(g_render.left) + canvasPoint.x, static_cast<float>(g_render.top) + canvasPoint.y };
    if (g_displayBounds.contains(screen)) return canvasPoint; // nearly every move: no monitors listed for it
    std::optional<Display> under = displayAt(screen);
    if (!under || under->bounds == g_displayBounds) return canvasPoint; // past the desktop's edge: held on this one
    if (g_settings) g_settings->islandMovedTo(under->id);
    placeIsland(under->id, screen);
    Vec2 moved{ screen.x - static_cast<float>(g_render.left), screen.y - static_cast<float>(g_render.top) };
    g_island.pointer.islandPress = moved;             // core measures the drag from where it came in
    g_drag = trackPointer({}, moved, now(), tokens()); // and so does the throw: not across two monitors' coordinates
    return moved;
}

// Settings turned the cover's colours on or off (decision 052). Off, the
// theme comes back at once, without the pause linger; on, the next dispatch
// picks up what's playing.
void setCoverColours(bool on)
{
    g_coverColours = on;
    if (!on) g_tint = {};
    Vec2 oldCanvas = tokens().canvas;
    if (app::setTint(g_tint.shown)) tokensChanged(oldCanvas, "cover colours");
    else dispatch(Tick{}, "cover colours");
}

// Glass (decision 089): the user's pick, as long as Windows' "Transparency
// effects" are on; off, the island is solid, like Windows' own surfaces.
void applyGlass(const char* reason)
{
    Vec2 oldCanvas = tokens().canvas;
    bool transparency = transparencyOn();
    if (g_glassPicked && !transparency) logLine("glass: picked, but Windows' transparency effects are off: solid");
    if (app::setGlass(g_glassPicked && transparency)) tokensChanged(oldCanvas, reason);
    app::setWindowsGlass(g_glassPicked && g_glassWindowsPicked && transparency); // decision 104
}

// The Settings card picked a theme: recolour everything (decision 022).
void applyTheme(const std::string& name)
{
    Vec2 oldCanvas = tokens().canvas;
    if (app::setTheme(name)) tokensChanged(oldCanvas, "theme");
}

